#!/usr/bin/env python3
"""Plot Fourier and interface evolution from nonlinear capillary-wave runs."""

from collections import defaultdict
import math
from pathlib import Path
import subprocess
import tempfile


def load_spectrum(path):
    modes = defaultdict(list)
    for line in Path(path).read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        tau, harmonic, _, _, _, normalized = map(float, line.split())
        modes[int(harmonic)].append((tau, normalized))
    return dict(modes)


def load_profiles(path):
    frames = {}
    tau = None
    segments = []
    segment = []
    for line in Path(path).read_text().splitlines():
        if line.startswith("# frame"):
            tau = float(line.split()[2])
            segments = []
        elif line.startswith("# end"):
            if segment:
                segments.append(segment)
                segment = []
            frames[tau] = segments
        elif not line:
            if segment:
                segments.append(segment)
                segment = []
        elif not line.startswith("#"):
            segment.append(tuple(map(float, line.split())))
    return frames


def load_grid_peaks(directory):
    directory = Path(directory)
    names = {
        32: "fourier-a0-{label}-N64.dat",
        64: "fourier-a0-{label}.dat",
        128: "fourier-a0-{label}-N256.dat",
    }
    peaks = {}
    for label in ("0.1", "0.5"):
        peaks[label] = {}
        for resolution, pattern in names.items():
            modes = load_spectrum(directory / pattern.format(label=label))
            peaks[label][resolution] = {
                harmonic: max(value for _, value in rows)
                for harmonic, rows in modes.items()
            }
    return peaks


WIDTH, HEIGHT = 1600, 900
COLORS = (
    "0.10 0.35 0.75",
    "0.85 0.20 0.16",
    "0.10 0.62 0.42",
    "0.65 0.22 0.78",
    "0.95 0.55 0.10",
    "0.15 0.65 0.72",
    "0.42 0.45 0.50",
    "0.55 0.32 0.16",
)


def _escaped(value):
    return value.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def _text(ps, x, y, value, size=20, color="0.13 0.17 0.23"):
    ps.append(
        f"{color} setrgbcolor /Helvetica findfont {size} scalefont setfont "
        f"{x:.2f} {HEIGHT-y:.2f} moveto ({_escaped(value)}) show"
    )


def _line(ps, x1, y1, x2, y2, color="0.84 0.87 0.90", stroke=1):
    ps.append(
        f"{color} setrgbcolor {stroke} setlinewidth newpath "
        f"{x1:.2f} {HEIGHT-y1:.2f} moveto {x2:.2f} {HEIGHT-y2:.2f} lineto stroke"
    )


def _polyline(ps, points, color, stroke=2):
    if not points:
        return
    ps.append(f"{color} setrgbcolor {stroke} setlinewidth 1 setlinejoin newpath")
    for index, (x, y) in enumerate(points):
        ps.append(f"{x:.2f} {HEIGHT-y:.2f} {'moveto' if index == 0 else 'lineto'}")
    ps.append("stroke")


def _header():
    return [
        "%!PS-Adobe-3.0",
        f"<< /PageSize [{WIDTH} {HEIGHT}] >> setpagedevice",
        "1 1 1 setrgbcolor clippath fill",
    ]


def _render(ps, output):
    ps.extend(["showpage", "%%EOF"])
    with tempfile.NamedTemporaryFile("w", suffix=".ps") as source:
        source.write("\n".join(ps))
        source.flush()
        subprocess.run(
            [
                "gs", "-q", "-dSAFER", "-dBATCH", "-dNOPAUSE",
                "-sDEVICE=png16m", "-r72", f"-g{WIDTH}x{HEIGHT}",
                "-dFIXEDMEDIA", f"-sOutputFile={output}", source.name,
            ],
            check=True,
        )


def _frame(ps, left, top, right, bottom):
    _line(ps, left, top, right, top, "0.35 0.40 0.47", 2)
    _line(ps, right, top, right, bottom, "0.35 0.40 0.47", 2)
    _line(ps, right, bottom, left, bottom, "0.35 0.40 0.47", 2)
    _line(ps, left, bottom, left, top, "0.35 0.40 0.47", 2)


def _mode_figure(cases, output):
    ps = _header()
    _text(ps, 100, 48, "Fourier harmonics generated by finite-amplitude waves", 34)
    xmax = max(t for modes, _ in cases.values() for rows in modes.values() for t, _ in rows)
    observed = max(v for modes, _ in cases.values() for rows in modes.values() for _, v in rows)
    ymax = max(1.1, math.ceil(observed*10.)/10.)

    for panel, (label, (modes, _)) in enumerate(cases.items()):
        left = 105 + panel*770
        right, top, bottom = left + 665, 115, 745
        px = lambda value: left + value/xmax*(right-left)
        py = lambda value: bottom - value/ymax*(bottom-top)
        _text(ps, left, 92, f"Initial amplitude a0 = {label}", 25)
        _frame(ps, left, top, right, bottom)
        for fraction in (0., 0.25, 0.5, 0.75, 1.):
            x = left + fraction*(right-left)
            _line(ps, x, top, x, bottom)
            _text(ps, x-12, bottom+28, f"{fraction*xmax:g}", 17)
        for fraction in (0., 0.25, 0.5, 0.75, 1.):
            value = fraction*ymax
            y = py(value)
            _line(ps, left, y, right, y)
            _text(ps, left-55, y+6, f"{value:.2g}", 17)
        for harmonic in range(1, 7):
            _polyline(
                ps,
                [(px(tau), py(value)) for tau, value in modes.get(harmonic, [])],
                COLORS[harmonic-1],
                2.5,
            )
        for harmonic in range(1, 7):
            x = left + 20 + ((harmonic-1) % 3)*205
            y = top + 28 + ((harmonic-1) // 3)*30
            _line(ps, x, y, x+35, y, COLORS[harmonic-1], 3)
            _text(ps, x+43, y+6, f"mode {harmonic}", 17)
        _text(ps, left+220, bottom+68, "Nondimensional time  tau", 21)
    ps.append(
        "gsave 31 305 translate 90 rotate 0.13 0.17 0.23 setrgbcolor "
        "/Helvetica findfont 22 scalefont setfont 0 0 moveto "
        "(Normalized Fourier magnitude  |A_n|/a0) show grestore"
    )
    _text(ps, 105, 865, "Mode 1 = original cosine wave; modes 2-8 = nonlinear harmonics", 19,
          "0.31 0.36 0.43")
    _render(ps, output)


def _heatmap_figure(cases, output):
    ps = _header()
    _text(ps, 100, 48, "Fourier-spectrum evolution", 34)
    xmax = max(t for modes, _ in cases.values() for rows in modes.values() for t, _ in rows)

    for panel, (label, (modes, _)) in enumerate(cases.items()):
        left = 105 + panel*770
        right, top, bottom = left + 665, 115, 680
        px = lambda value: left + value/xmax*(right-left)
        row_height = (bottom-top)/8.
        _text(ps, left, 92, f"Initial amplitude a0 = {label}", 25)
        for harmonic in range(1, 9):
            rows = modes[harmonic]
            step = rows[1][0] - rows[0][0] if len(rows) > 1 else xmax
            y1 = top + (harmonic-1)*row_height
            y2 = y1 + row_height
            for tau, value in rows:
                level = (math.log10(max(value, 1e-4)) + 4.)/4.
                level = min(1., max(0., level))
                red = 0.08 + 0.90*level
                green = 0.18 + 0.58*(1.-abs(2.*level-1.))
                blue = 0.70*(1.-level) + 0.08
                x1, x2 = px(tau), px(min(xmax, tau+step))
                ps.append(
                    f"{red:.3f} {green:.3f} {blue:.3f} setrgbcolor "
                    f"{x1:.2f} {HEIGHT-y2:.2f} {max(0.5, x2-x1):.2f} "
                    f"{row_height:.2f} rectfill"
                )
            _text(ps, left-38, (y1+y2)/2+6, str(harmonic), 18)
        _frame(ps, left, top, right, bottom)
        for fraction in (0., 0.25, 0.5, 0.75, 1.):
            x = left + fraction*(right-left)
            _line(ps, x, bottom, x, bottom+7, "0.20 0.24 0.30", 1)
            _text(ps, x-12, bottom+28, f"{fraction*xmax:g}", 17)
        _text(ps, left+220, bottom+68, "Nondimensional time  tau", 21)
    ps.append(
        "gsave 35 335 translate 90 rotate 0.13 0.17 0.23 setrgbcolor "
        "/Helvetica findfont 22 scalefont setfont 0 0 moveto "
        "(Harmonic number n) show grestore"
    )
    for index, exponent in enumerate((-4, -3, -2, -1, 0)):
        level = index/4.
        red = 0.08 + 0.90*level
        green = 0.18 + 0.58*(1.-abs(2.*level-1.))
        blue = 0.70*(1.-level) + 0.08
        x = 570 + index*100
        ps.append(
            f"{red:.3f} {green:.3f} {blue:.3f} setrgbcolor "
            f"{x} 55 100 22 rectfill"
        )
        _text(ps, x+30, 838, f"1e{exponent}", 16)
    _text(ps, 365, 816, "|A_n|/a0", 18)
    _render(ps, output)


def _profile_figure(cases, output):
    ps = _header()
    _text(ps, 100, 48, "Interface evolution", 34)
    all_y = [
        y
        for _, frames in cases.values()
        for segments in frames.values()
        for segment in segments
        for _, y in segment
    ]
    ymax = max(0.55, max(abs(value) for value in all_y)*1.08)

    for panel, (label, (_, frames)) in enumerate(cases.items()):
        left = 105 + panel*770
        right, top, bottom = left + 665, 115, 745
        px = lambda value: left + value/2.*(right-left)
        py = lambda value: (top+bottom)/2. - value/ymax*(bottom-top)/2.
        _text(ps, left, 92, f"Initial amplitude a0 = {label}", 25)
        _frame(ps, left, top, right, bottom)
        _line(ps, left, py(0), right, py(0), "0.55 0.59 0.64", 1)
        for value in (0., 0.5, 1., 1.5, 2.):
            x = px(value)
            _line(ps, x, top, x, bottom)
            _text(ps, x-8, bottom+28, f"{value:g}", 17)
        for value in (-ymax, -ymax/2., 0., ymax/2., ymax):
            y = py(value)
            _text(ps, left-65, y+6, f"{value:.2g}", 17)
        for index, (tau, segments) in enumerate(sorted(frames.items())):
            color = COLORS[index % len(COLORS)]
            for segment in segments:
                _polyline(ps, [(px(x), py(y)) for x, y in segment], color, 1.8)
            x = left + 18 + (index % 3)*205
            y = top + 28 + (index//3)*29
            _line(ps, x, y, x+30, y, color, 2.5)
            _text(ps, x+38, y+6, f"tau={tau:g}", 16)
        _text(ps, left+315, bottom+68, "x", 21)
    ps.append(
        "gsave 37 390 translate 90 rotate 0.13 0.17 0.23 setrgbcolor "
        "/Helvetica findfont 22 scalefont setfont 0 0 moveto "
        "(Interface height y) show grestore"
    )
    _text(ps, 105, 865, "Profiles sampled every 5 nondimensional time units", 19,
          "0.31 0.36 0.43")
    _render(ps, output)


def render_grid_convergence(directory=Path(".")):
    directory = Path(directory)
    peaks = load_grid_peaks(directory)
    output = directory / "fourier-grid-convergence.png"
    ps = _header()
    _text(ps, 100, 48, "Grid sensitivity of peak Fourier modes", 34)
    harmonics = (1, 3, 5, 7)
    resolutions = (32, 64, 128)
    ymin, ymax = -4., math.log10(1.2)

    for panel, label in enumerate(("0.1", "0.5")):
        left = 105 + panel*770
        right, top, bottom = left + 665, 115, 745
        px = lambda value: left + (math.log2(value)-5.)/2.*(right-left)
        py = lambda value: bottom - (math.log10(max(value, 1e-4))-ymin)/(ymax-ymin)*(bottom-top)
        _text(ps, left, 92, f"Initial amplitude a0 = {label}", 25)
        _frame(ps, left, top, right, bottom)
        for resolution in resolutions:
            x = px(resolution)
            _line(ps, x, top, x, bottom)
            _text(ps, x-14, bottom+28, str(resolution), 17)
        for exponent in range(-4, 1):
            y = py(10.**exponent)
            _line(ps, left, y, right, y)
            _text(ps, left-58, y+6, f"1e{exponent}", 17)
        for index, harmonic in enumerate(harmonics):
            points = [
                (px(resolution), py(peaks[label][resolution][harmonic]))
                for resolution in resolutions
            ]
            _polyline(ps, points, COLORS[index], 3)
            for x, y in points:
                ps.append(
                    f"{COLORS[index]} setrgbcolor newpath "
                    f"{x:.2f} {HEIGHT-y:.2f} 5 0 360 arc fill"
                )
            x = left + 25 + index*150
            y = top + 30
            _line(ps, x, y, x+32, y, COLORS[index], 3)
            _text(ps, x+40, y+6, f"mode {harmonic}", 16)
        _text(ps, left+190, bottom+68, "Cells per wavelength", 21)
    ps.append(
        "gsave 28 245 translate 90 rotate 0.13 0.17 0.23 setrgbcolor "
        "/Helvetica findfont 21 scalefont setfont 0 0 moveto "
        "(Peak normalized magnitude) show grestore"
    )
    _text(ps, 105, 865,
          "32, 64, 128 cells/lambda; flatter curves indicate grid-independent peaks",
          19, "0.31 0.36 0.43")
    _render(ps, output)
    return output


def render_all(directory=Path(".")):
    directory = Path(directory)
    cases = {
        label: (
            load_spectrum(directory / f"fourier-a0-{label}.dat"),
            load_profiles(directory / f"profiles-a0-{label}.dat"),
        )
        for label in ("0.1", "0.5")
    }
    outputs = [
        directory / "fourier-mode-evolution.png",
        directory / "fourier-spectrum-heatmap.png",
        directory / "interface-evolution.png",
    ]
    _mode_figure(cases, outputs[0])
    _heatmap_figure(cases, outputs[1])
    _profile_figure(cases, outputs[2])
    return outputs


if __name__ == "__main__":
    root = Path(__file__).resolve().parent
    figures = render_all(root)
    grid_files = [
        root / f"fourier-a0-{label}-N{grid}.dat"
        for label in ("0.1", "0.5")
        for grid in (64, 256)
    ]
    if all(path.exists() for path in grid_files):
        figures.append(render_grid_convergence(root))
    for figure in figures:
        print(figure.name)
